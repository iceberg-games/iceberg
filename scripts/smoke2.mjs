import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = []; p.on('console', m => m.type() === 'error' && errs.push(m.text())); p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + process.cwd() + '/dist/index.html');
await p.click('#start-btn'); await p.waitForSelector('.game-card');
console.log('cards', await p.$$eval('.game-card .gc-name', e => e.map(x => x.textContent)));
await p.evaluate(() => window.iceberg.play('birg-hq')); await p.waitForTimeout(1200);
// walk up stairs: teleport near stair bottom and walk -x
await p.evaluate(() => { const pl = window.iceberg.engine.player; pl.teleport(new pl.pos.constructor(7.1, 0, -3.2), 0); pl.camYaw = 0; });
await p.keyboard.down('KeyW'); await p.waitForTimeout(400); await p.keyboard.up('KeyW');
await p.evaluate(() => { window.iceberg.engine.player.camYaw = Math.PI/2; });
await p.keyboard.down('KeyW'); await p.waitForTimeout(2500); await p.keyboard.up('KeyW');
console.log('hq pos after stairs', await p.evaluate(() => window.iceberg.engine.player.pos.toArray().map(v=>v.toFixed(2))));
await p.evaluate(() => window.iceberg.goHome());
await p.evaluate(() => window.iceberg.play('rainbow-obby')); await p.waitForTimeout(1000);
console.log('obby label', await p.textContent('.obby-label'));
await p.evaluate(() => window.iceberg.economy.demoGrant(100));
await p.click('#skip-stage'); await p.waitForTimeout(300);
console.log('after skip', await p.textContent('.obby-label'), await p.evaluate(() => window.iceberg.engine.player.pos.toArray()));
await p.evaluate(() => window.iceberg.engine.player.teleport(new (window.iceberg.engine.player.pos.constructor)(5, 0.5, 20)));
await p.waitForTimeout(800);
console.log('lava respawn ->', await p.evaluate(() => window.iceberg.engine.player.pos.toArray()));
// store demo
await p.click('#btn-store'); const before = await p.evaluate(() => window.iceberg.economy.coins);
await p.click('[data-pack=bb_500] .price-btn'); 
console.log('demo buy', before, '->', await p.evaluate(() => window.iceberg.economy.coins), await p.textContent('#pay-notice'));
await p.click('#drawer-close');
await p.evaluate(() => { const e = window.iceberg.economy; e.demoGrant(100000); e.buy('icerocket'); e.equip('icerocket'); e.setRocketColor('body', '#ff0000'); });
await p.keyboard.down('KeyF'); await p.waitForTimeout(700);
console.log('flying', await p.evaluate(() => [window.iceberg.engine.player.flying, !!window.iceberg.music._rocket, window.iceberg.engine.player.pos.y.toFixed(1)]));
await p.keyboard.up('KeyF');
await p.evaluate(() => window.iceberg.goHome());
await p.click('#create-btn'); await p.click('[data-template=blank]'); await p.waitForTimeout(1000);
await p.mouse.click(640, 600); await p.mouse.click(600, 620); await p.waitForTimeout(300);
console.log('studio blocks', await p.evaluate(() => window.iceberg.engine.game.building.count));
await p.click('#save-game'); await p.click('#exit-editor'); await p.waitForTimeout(300);
await p.click('#your-games .play'); await p.waitForTimeout(1000);
console.log('playing custom', await p.evaluate(() => [window.iceberg.engine.def.name, window.iceberg.engine.game.building.count]));
console.log('errors', errs);
await b.close();
